const ADDED = "2026-10-28";

type Seed = {
  id: string;
  name: string;
  category: Broker["category"];
  blurb: string;
  optOutUrl: string;
  homeUrl?: string;
  email?: string;
  steps: string[];
  difficulty?: Difficulty;
  requiresEmail?: boolean;
  requiresId?: boolean;
  requiresPhone?: boolean;
  letterRecommended?: boolean;
  verification?: Verification;
  notes?: string;
};

function card(seed: Seed): Broker {
  const verification = seed.verification ?? "ok";
  return {
    id: seed.id,
    name: seed.name,
    category: seed.category,
    blurb: seed.blurb,
    optOutUrl: seed.optOutUrl,
    ...(seed.homeUrl ? { homeUrl: seed.homeUrl } : {}),
    ...(seed.email ? { email: seed.email } : {}),
    steps: seed.steps,
    difficulty: seed.difficulty ?? "medium",
    requiresEmail: seed.requiresEmail ?? true,
    requiresId: seed.requiresId ?? false,
    requiresPhone: seed.requiresPhone ?? false,
    letterRecommended: seed.letterRecommended ?? false,
    lastVerified: verification === "failed" ? null : ADDED,
    verification,
    ...(seed.notes ? { notes: seed.notes } : {}),
  };
}

function mail(address: string): string {
  return `[${address}](mailto:${address})`;
}

function peopleForm(site: string): string[] {
  return [
    `Open the ${site} opt-out page.`,
    "Search your name and open the listing that is you.",
    "Submit the form with an email you can open.",
    "Click the confirmation link if they send one.",
  ];
}

function blockedForm(site: string): string[] {
  return [
    `Open the ${site} opt-out page in your browser. A security check stopped our automated visit. This is still the address they publish.`,
    "Search your name and open the listing that is you.",
    "Submit the form with an email you can open.",
    "Click the confirmation link if they send one.",
  ];
}

function blockedUnknown(site: string): string[] {
  return [
    `Open ${site} in your browser. The site blocked an automated check, so a removal form could not be read.`,
    "Look for a privacy, opt-out, or do-not-sell link, usually in the footer.",
    "If you find a form, submit it with an email you can open.",
    "If there is no form, use the letter page and ask them to delete your information.",
  ];
}

function noForm(site: string): string[] {
  return [
    `Open ${site}. A public removal form was not found on October 28, 2026.`,
    "Look in the footer for a privacy or opt-out link, in case they added one.",
    "If there is still no form, use the letter page and ask them to delete your information.",
    "Mark this Submitted when you send it, then check again later.",
  ];
}

function privacyMail(site: string, address: string): string[] {
  return [
    `Open the ${site} privacy page.`,
    `Email ${mail(address)} and ask them to delete your information and stop selling it.`,
    "Include your name and the addresses or emails they might have on file.",
    "If you do not hear back, use the letter page and follow up after about 45 days.",
  ];
}

