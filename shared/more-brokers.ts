function marketingForm(entry: FormBroker): Broker {
  const steps = [
    `Open the ${entry.name} opt-out page.`,
    "Enter your name and the contact details you want removed.",
    entry.email
      ? `You can also email ${mail(entry.email)} with the same request.`
      : "Use an email you can open, if the form asks for one.",
    "Save the confirmation. Follow the link if they email you.",
  ];
  return card({
    id: entry.id,
    name: entry.name,
    category: "marketing",
    blurb: entry.blurb,
    optOutUrl: entry.optOutUrl,
    homeUrl: entry.homeUrl,
    email: entry.email,
    steps,
    difficulty: "easy",
    letterRecommended: entry.letterRecommended ?? false,
    notes: entry.notes,
  });
}

function marketingLetter(entry: {
  id: string;
  name: string;
  blurb: string;
  optOutUrl: string;
  homeUrl?: string;
  email?: string;
  verification?: Verification;
  notes?: string;
  blocked?: boolean;
}): Broker {
  const steps = entry.email
    ? entry.blocked
      ? [
          `Open the ${entry.name} page in your browser. It blocked an automated check.`,
          `Their published privacy address is ${mail(entry.email)}. Confirm it on the page, then ask them to delete your information.`,
          "Include your name and the addresses or emails they might have.",
          "If you cannot use the page, send the same request from the letter page.",
        ]
      : privacyMail(entry.name, entry.email)
    : entry.blocked
      ? [
          `Open the ${entry.name} privacy page in your browser. It blocked an automated check.`,
          "Look for a privacy email or a do-not-sell form.",
          "If you find one, ask them to delete your information and not sell it.",
          "If the page will not load, use the letter page.",
        ]
      : noForm(entry.name);
  return card({
    id: entry.id,
    name: entry.name,
    category: "marketing",
    blurb: entry.blurb,
    optOutUrl: entry.optOutUrl,
    homeUrl: entry.homeUrl,
    email: entry.email,
    steps,
    letterRecommended: true,
    verification: entry.verification ?? (entry.blocked ? "blocked" : "ok"),
    notes: entry.notes,
  });
}

