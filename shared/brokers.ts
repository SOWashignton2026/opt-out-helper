/**
 * People-search sites and call/junk-mail tasks.
 * Edit this file to add a site. Keep one object per row.
 *
 * verification:
 * - ok: we opened the page, or read the company's own page naming this address
 * - blocked: the usual official address, but the site refused our automated check
 * - failed: we could not confirm a working removal page (see notes)
 *
 * Checked on 2026-10-19. New and changed links were checked again on 2026-10-22.
 *
 * In steps, link a form or page with [label](https://example.com) or
 * [name@example.com](mailto:name@example.com). The Privacy Tool turns those into links.
 *
 * letterRecommended: true when the practical route is an email, a letter, or a
 * state-privacy deletion request. Simple web forms stay false.
 */
export type Difficulty = "easy" | "medium" | "hard";
export type Category = "people-search" | "spam" | "marketing" | "search" | "nonpublic";
export type Verification = "ok" | "blocked" | "failed";

export type Broker = {
  id: string;
  name: string;
  category: Category;
  blurb: string;
  optOutUrl: string;
  /** Public search or home page when it is not the opt-out host. */
  homeUrl?: string;
  /** Tokens: {firstSlug} {lastSlug} {nameSlug} {firstLower} {lastLower} {citySlug} {cityLower} {city} {state} {stateLower} {stateName} {phone} */
  searchUrlTemplate?: string;
  phoneSearchUrl?: string;
  steps: string[];
  difficulty: Difficulty;
  requiresEmail: boolean;
  requiresId: boolean;
  requiresPhone: boolean;
  /** True when a written request is the useful route, not a simple opt-out form. */
  letterRecommended: boolean;
  /** The site often refuses people outside states with a consumer privacy law. */
  stateLimited?: boolean;
  /** True when the opt-out link itself could not be confirmed. */
  linkNotVerified?: boolean;
  /** Privacy inbox for email-only brokers. The card copies this address. */
  email?: string;
  /** YYYY-MM-DD when the link checked out, or null when verification is failed. */
  lastVerified: string | null;
  verification: Verification;
  notes?: string;
};

const CHECKED = "2026-10-19";
const RECHECKED = "2026-10-22";
const BATCH4 = "2026-10-23";
const DELETE_SUBJECT = "Request to delete my personal information";

function privacyMailto(address: string): string {
  return `mailto:${address}?subject=${encodeURIComponent(DELETE_SUBJECT)}`;
}

function emailSteps(address: string): string[] {
  return [
    `Email ${address} with the subject "${DELETE_SUBJECT}".`,
    "Include your name, address, email, and phone. Ask them to delete your information and to opt out of selling it.",
    "Reply to any verification email they send.",
    "If you do not hear back, follow up after about 45 days.",
  ];
}

function emailBroker(entry: {
  id: string;
  name: string;
  email: string;
  blurb: string;
  stateLimited?: boolean;
  notes?: string;
}): Broker {
  return {
    id: entry.id,
    name: entry.name,
    category: "nonpublic",
    blurb: entry.blurb,
    email: entry.email,
    optOutUrl: privacyMailto(entry.email),
    steps: emailSteps(entry.email),
    difficulty: "medium",
    requiresEmail: true,
    requiresId: false,
    requiresPhone: false,
    letterRecommended: true,
    ...(entry.stateLimited ? { stateLimited: true } : {}),
    lastVerified: BATCH4,
    verification: "ok",
    notes: entry.notes,
  };
}

